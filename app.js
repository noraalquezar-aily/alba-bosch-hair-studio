// --- TRANSLATION CORE ENGINE ---
function initLanguage() {
  const savedLang = localStorage.getItem("preferred_language");
  if (savedLang && translations[savedLang]) {
    currentLanguage = savedLang;
  } else {
    // Detect browser language if matches
    const browserLang = navigator.language.slice(0, 2);
    if (translations[browserLang]) {
      currentLanguage = browserLang;
    }
  }
  
  applyTranslations(currentLanguage);
  
  // Set up event listeners for lang buttons
  const langButtons = document.querySelectorAll(".lang-dropdown button");
  langButtons.forEach(btn => {
    btn.addEventListener("click", (e) => {
      const selectedLang = e.currentTarget.getAttribute("data-lang");
      if (translations[selectedLang]) {
        currentLanguage = selectedLang;
        localStorage.setItem("preferred_language", selectedLang);
        applyTranslations(selectedLang);
      }
    });
  });

  // Toggle lang dropdown on click (mobile/touch support)
  const langTrigger = document.querySelector(".lang-trigger");
  const langSelector = document.querySelector(".lang-selector");
  if (langTrigger && langSelector) {
    langTrigger.addEventListener("click", (e) => {
      e.stopPropagation();
      langSelector.classList.toggle("active");
    });
    
    // Close dropdown when clicking outside
    document.addEventListener("click", () => {
      langSelector.classList.remove("active");
    });
  }
}

function applyTranslations(lang) {
  // Fade transition effect
  const mainContent = document.body;
  mainContent.style.opacity = "0.7";
  mainContent.style.transition = "opacity 0.2s ease";
  
  setTimeout(() => {
    // Update simple translations
    const elements = document.querySelectorAll("[data-i18n]");
    elements.forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (translations[lang][key]) {
        el.innerHTML = translations[lang][key];
      }
    });

    // Update placeholder translations
    const placeholderInputs = document.querySelectorAll("[data-i18n-placeholder]");
    placeholderInputs.forEach(input => {
      const key = input.getAttribute("data-i18n-placeholder");
      if (translations[lang][key]) {
        input.setAttribute("placeholder", translations[lang][key]);
      }
    });

    // Update lang trigger text
    const activeLangText = document.querySelector(".active-lang-text");
    if (activeLangText) {
      activeLangText.textContent = lang.toUpperCase();
    }

    // Set active class on lang button
    document.querySelectorAll(".lang-dropdown button").forEach(btn => {
      if (btn.getAttribute("data-lang") === lang) {
        btn.classList.add("active");
      } else {
        btn.classList.remove("active");
      }
    });

    // Notify listeners that language has updated
    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang: lang } }));

    mainContent.style.opacity = "1";
  }, 200);
}

