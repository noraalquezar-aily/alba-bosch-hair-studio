// --- BEFORE & AFTER 3D CAROUSEL AND SLIDERS ---
function initBeforeAfterSlider() {
  const slides = document.querySelectorAll(".carousel-slide");
  const dots = document.querySelectorAll(".carousel-dots .dot");
  const arrowPrev = document.querySelector(".carousel-arrow.arrow-prev");
  const arrowNext = document.querySelector(".carousel-arrow.arrow-next");
  const track = document.querySelector(".carousel-track");
  const activeTitle = document.getElementById("carousel-active-title");
  
  const captionKeys = [
    "caption_balayage",
    "caption_copper",
    "caption_blonde",
    "caption_chocolate",
    "caption_gloss"
  ];
  
  if (slides.length === 0) return;

  let activeIndex = 0;
  const totalSlides = slides.length;

  // 1. Initialize sliders on each slide independently
  slides.forEach((slide) => {
    const slider = slide.querySelector(".comparison-slider");
    const handle = slide.querySelector(".slider-handle");
    if (!slider || !handle) return;

    let isDragging = false;

    const updateSlider = (clientX) => {
      // Only allow slider interaction if this slide is active in the center
      if (!slide.classList.contains("active")) return;
      
      const rect = slider.getBoundingClientRect();
      const x = clientX - rect.left;
      let percentage = (x / rect.width) * 100;

      if (percentage < 0) percentage = 0;
      if (percentage > 100) percentage = 100;

      slider.style.setProperty("--clip-pos", `${percentage}%`);
    };

    // Mouse events
    handle.addEventListener("mousedown", (e) => {
      if (!slide.classList.contains("active")) return;
      isDragging = true;
      e.preventDefault();
      e.stopPropagation();
    });

    window.addEventListener("mousemove", (e) => {
      if (!isDragging) return;
      updateSlider(e.clientX);
    });

    window.addEventListener("mouseup", () => {
      isDragging = false;
    });

    // Touch events for mobile dragging
    handle.addEventListener("touchstart", (e) => {
      if (!slide.classList.contains("active")) return;
      isDragging = true;
      e.preventDefault();
      e.stopPropagation();
    }, { passive: false });

    window.addEventListener("touchmove", (e) => {
      if (!isDragging) return;
      if (e.touches.length > 0) {
        updateSlider(e.touches[0].clientX);
      }
    }, { passive: false });

    window.addEventListener("touchend", () => {
      isDragging = false;
    });

    // Clicks on slider track to jump
    slider.addEventListener("click", (e) => {
      if (!slide.classList.contains("active")) return;
      if (e.target === handle || handle.contains(e.target)) return;
      updateSlider(e.clientX);
    });
  });

  // 2. Carousel navigation logic
  const updateCarousel = (newIndex) => {
    // Keep index circular
    activeIndex = (newIndex + totalSlides) % totalSlides;

    // Update slides classes
    slides.forEach((slide, idx) => {
      slide.className = "carousel-slide"; // Reset classes
      
      // Reset slider split position to exactly 50%
      const sliderEl = slide.querySelector(".comparison-slider");
      if (sliderEl) {
        sliderEl.style.setProperty("--clip-pos", "50%");
      }
      
      // Calculate circular distance from activeIndex
      let diff = (idx - activeIndex + totalSlides) % totalSlides;
      
      if (diff === 0) {
        slide.classList.add("active");
      } else if (diff === 1) {
        slide.classList.add("next");
      } else if (diff === 2) {
        slide.classList.add("next2");
      } else if (diff === totalSlides - 2) {
        slide.classList.add("prev2");
      } else if (diff === totalSlides - 1) {
        slide.classList.add("prev");
      } else {
        slide.classList.add("hidden");
      }
    });

    // Update dots indicators
    dots.forEach((dot, idx) => {
      if (idx === activeIndex) {
        dot.classList.add("active");
      } else {
        dot.classList.remove("active");
      }
    });

    // Update active slide caption
    if (activeTitle) {
      const key = captionKeys[activeIndex];
      activeTitle.setAttribute("data-i18n", key);
      activeTitle.textContent = getTranslatedText(key);
    }
  };

  // Event Listeners for arrows
  if (arrowPrev) {
    arrowPrev.addEventListener("click", (e) => {
      e.preventDefault();
      updateCarousel(activeIndex - 1);
    });
  }

  if (arrowNext) {
    arrowNext.addEventListener("click", (e) => {
      e.preventDefault();
      updateCarousel(activeIndex + 1);
    });
  }

  // Event Listeners for dots
  dots.forEach((dot) => {
    dot.addEventListener("click", () => {
      const targetIndex = parseInt(dot.getAttribute("data-index"));
      updateCarousel(targetIndex);
    });
  });

  // 3. Touch Swipe gesture detection (for carousel switching on mobile/tablets)
  if (track) {
    let touchStartX = 0;
    let touchEndX = 0;
    let isTouchOnHandle = false;

    track.addEventListener("touchstart", (e) => {
      if (e.target.closest(".slider-handle")) {
        isTouchOnHandle = true;
        return;
      }
      isTouchOnHandle = false;
      touchStartX = e.touches[0].clientX;
    }, { passive: true });

    track.addEventListener("touchend", (e) => {
      if (isTouchOnHandle) return;
      touchEndX = e.changedTouches[0].clientX;
      const swipeDistance = touchEndX - touchStartX;
      
      if (swipeDistance > 50) {
        updateCarousel(activeIndex - 1);
      } else if (swipeDistance < -50) {
        updateCarousel(activeIndex + 1);
      }
    }, { passive: true });
  }

  // Listen for language changes to update active title text content
  window.addEventListener("languageChanged", () => {
    if (activeTitle) {
      const key = captionKeys[activeIndex];
      activeTitle.textContent = getTranslatedText(key);
    }
  });

  // Set initial state
  updateCarousel(0);
}

// --- SHOPPING CART & CHECKOUT SYSTEMS ---
function initCartAndCheckout() {
  let cart = [];
  let isDiscountApplied = false;

  const products = {
    shampoo: { name_key: "product_shampoo_name", price: 28, img: "assets/product-shampoo.jpg" },
    oil: { name_key: "product_oil_name", price: 34, img: "assets/product-oil.jpg" },
    cream: { name_key: "product_cream_name", price: 30, img: "assets/product-cream.jpg" }
  };

  // Selectors
  const cartTrigger = document.querySelector(".cart-trigger");
  const cartDrawer = document.querySelector(".cart-drawer");
  const cartBackdrop = document.querySelector(".cart-backdrop");
  const cartCloseBtn = document.querySelector(".cart-close-btn");
  const cartItemsContainer = document.getElementById("cart-items-container");
  const cartSubtotalVal = document.getElementById("cart-subtotal-val");
  const cartShippingVal = document.getElementById("cart-shipping-val");
  const cartTotalVal = document.getElementById("cart-total-val");
  const cartCountBadge = document.querySelector(".cart-count");
  const cartCheckoutBtn = document.getElementById("cart-checkout-btn");
  const cartDiscountRow = document.getElementById("cart-discount-row");
  const cartDiscountVal = document.getElementById("cart-discount-val");
  const cartPromoInput = document.getElementById("cart-promo-input");
  const cartPromoApply = document.getElementById("cart-promo-apply");
  const cartPromoFeedback = document.getElementById("cart-promo-feedback");

  const checkoutOverlay = document.querySelector(".checkout-overlay");
  const checkoutCloseBtn = document.querySelector(".checkout-close");
  const checkoutItemsSummary = document.getElementById("checkout-items-summary");
  const checkoutSubtotalVal = document.getElementById("checkout-subtotal-val");
  const checkoutShippingVal = document.getElementById("checkout-shipping-val");
  const checkoutDiscountRow = document.getElementById("checkout-discount-row");
  const checkoutDiscountVal = document.getElementById("checkout-discount-val");
  const checkoutTotalVal = document.getElementById("checkout-total-val");
  const checkoutPromoInput = document.getElementById("checkout-promo-input");
  const checkoutPromoApply = document.getElementById("checkout-promo-apply");
  const checkoutPromoFeedback = document.getElementById("checkout-promo-feedback");
  const checkoutForm = document.getElementById("checkout-form");
  const checkoutMainGrid = document.getElementById("checkout-main-grid");
  const checkoutSuccessContainer = document.getElementById("checkout-success-container");
  const checkoutSuccessClose = document.getElementById("checkout-success-close");

  const paymentOptions = document.querySelectorAll(".payment-option-card");
  const cardDetailsFields = document.getElementById("card-details-fields");

  // Quantity control buttons on product cards
  const qtyMinuses = document.querySelectorAll(".product-quantity-control .qty-minus");
  const qtyPluses = document.querySelectorAll(".product-quantity-control .qty-plus");

  qtyMinuses.forEach(btn => {
    btn.addEventListener("click", (e) => {
      const input = e.target.parentElement.querySelector(".qty-input");
      let val = parseInt(input.value);
      if (val > 1) {
        input.value = val - 1;
      }
    });
  });

  qtyPluses.forEach(btn => {
    btn.addEventListener("click", (e) => {
      const input = e.target.parentElement.querySelector(".qty-input");
      let val = parseInt(input.value);
      input.value = val + 1;
    });
  });

  // Add to cart buttons
  const addToCartBtns = document.querySelectorAll(".add-to-cart-btn");
  addToCartBtns.forEach(btn => {
    btn.addEventListener("click", (e) => {
      const productId = e.target.getAttribute("data-product-id");
      const card = e.target.closest(".product-card");
      const input = card.querySelector(".qty-input");
      const quantity = parseInt(input.value);

      addToCart(productId, quantity);
      
      // Reset product card quantity back to 1
      input.value = 1;
    });
  });

  // Open/Close Cart Drawer
  if (cartTrigger) {
    cartTrigger.addEventListener("click", () => {
      cartDrawer.classList.add("active");
      cartBackdrop.classList.add("active");
    });
  }

  const closeCart = () => {
    cartDrawer.classList.remove("active");
    cartBackdrop.classList.remove("active");
  };

  if (cartCloseBtn) cartCloseBtn.addEventListener("click", closeCart);
  if (cartBackdrop) cartBackdrop.addEventListener("click", closeCart);

  // Cart Logic
  function addToCart(id, qty) {
    const existing = cart.find(item => item.id === id);
    if (existing) {
      existing.qty += qty;
    } else {
      const prod = products[id];
      cart.push({
        id,
        name: getTranslatedText(prod.name_key),
        price: prod.price,
        qty: qty,
        img: prod.img
      });
    }
    updateCartUI();
    
    // Open drawer automatically
    cartDrawer.classList.add("active");
    cartBackdrop.classList.add("active");
  }



  function removeFromCart(id) {
    cart = cart.filter(item => item.id !== id);
    updateCartUI();
  }

  function updateQuantity(id, qty) {
    const item = cart.find(item => item.id === id);
    if (item) {
      item.qty = Math.max(1, qty);
    }
    updateCartUI();
  }

  function updateCartUI() {
    // Update count badge
    const totalCount = cart.reduce((acc, item) => acc + item.qty, 0);
    if (cartCountBadge) {
      cartCountBadge.textContent = totalCount;
    }

    // Render items list
    if (!cartItemsContainer) return;
    
    if (cart.length === 0) {
      cartItemsContainer.innerHTML = `<p class="cart-empty-message" data-i18n="cart_empty">${getTranslatedText("cart_empty")}</p>`;
      if (cartCheckoutBtn) cartCheckoutBtn.disabled = true;
    } else {
      if (cartCheckoutBtn) cartCheckoutBtn.disabled = false;
      
      cartItemsContainer.innerHTML = "";
      cart.forEach(item => {
        const itemEl = document.createElement("div");
        itemEl.className = "cart-item";
        itemEl.innerHTML = `
          <img src="${item.img}" alt="${item.name}" class="cart-item-img">
          <div class="cart-item-details">
            <h4 class="cart-item-name">${item.name}</h4>
            <span class="cart-item-price">${item.price}€</span>
            <div class="cart-item-qty-control">
              <button class="qty-btn qty-minus">−</button>
              <input type="number" class="qty-input" value="${item.qty}" min="1" readonly>
              <button class="qty-btn qty-plus">+</button>
            </div>
            <a class="cart-item-remove" data-id="${item.id}" data-i18n="cart_item_remove">${currentLanguage === "en" ? "Remove" : currentLanguage === "es" ? "Eliminar" : "Eliminar"}</a>
          </div>
        `;

        // Bind events for item quantity control
        const itemMinus = itemEl.querySelector(".qty-minus");
        const itemPlus = itemEl.querySelector(".qty-plus");
        const itemRemove = itemEl.querySelector(".cart-item-remove");

        itemMinus.addEventListener("click", () => {
          updateQuantity(item.id, item.qty - 1);
        });
        itemPlus.addEventListener("click", () => {
          updateQuantity(item.id, item.qty + 1);
        });
        itemRemove.addEventListener("click", () => {
          removeFromCart(item.id);
        });

        cartItemsContainer.appendChild(itemEl);
      });
    }

    // Compute Totals
    const subtotal = cart.reduce((acc, item) => acc + (item.price * item.qty), 0);
    const shipping = (subtotal === 0 || subtotal >= 50) ? 0 : 4.90;
    let total = subtotal + shipping;

    if (isDiscountApplied) {
      total = (subtotal * 0.9) + shipping;
    }

    // Update Cart Panel display values
    if (cartSubtotalVal) cartSubtotalVal.textContent = `${subtotal.toFixed(2)}€`;
    if (cartShippingVal) cartShippingVal.textContent = shipping === 0 ? "FREE" : `${shipping.toFixed(2)}€`;
    
    if (isDiscountApplied) {
      const discount = subtotal * 0.1;
      if (cartDiscountRow) cartDiscountRow.style.display = "flex";
      if (cartDiscountVal) cartDiscountVal.textContent = `-${discount.toFixed(2)}€`;
      if (checkoutDiscountRow) checkoutDiscountRow.style.display = "flex";
      if (checkoutDiscountVal) checkoutDiscountVal.textContent = `-${discount.toFixed(2)}€`;
    } else {
      if (cartDiscountRow) cartDiscountRow.style.display = "none";
      if (checkoutDiscountRow) checkoutDiscountRow.style.display = "none";
    }
    
    if (cartTotalVal) cartTotalVal.textContent = `${total.toFixed(2)}€`;

    // Update Checkout Modal displays if open
    if (checkoutSubtotalVal) checkoutSubtotalVal.textContent = `${subtotal.toFixed(2)}€`;
    if (checkoutShippingVal) checkoutShippingVal.textContent = shipping === 0 ? "FREE" : `${shipping.toFixed(2)}€`;
    if (checkoutTotalVal) checkoutTotalVal.textContent = `${total.toFixed(2)}€`;

    // Re-translate cart items if language changed
    cart.forEach(item => {
      const prod = products[item.id];
      item.name = getTranslatedText(prod.name_key);
    });
  }

  // Bind cart changes to language switching
  window.addEventListener("languageChanged", () => {
    updateCartUI();
  });

  // Open Checkout Modal
  if (cartCheckoutBtn) {
    cartCheckoutBtn.addEventListener("click", () => {
      closeCart();
      checkoutOverlay.classList.add("active");
      renderCheckoutSummary();
    });
  }

  const closeCheckout = () => {
    checkoutOverlay.classList.remove("active");
    // reset checkout screens
    checkoutMainGrid.style.display = "grid";
    checkoutSuccessContainer.style.display = "none";
  };

  if (checkoutCloseBtn) checkoutCloseBtn.addEventListener("click", closeCheckout);
  if (checkoutSuccessClose) checkoutSuccessClose.addEventListener("click", closeCheckout);

  function renderCheckoutSummary() {
    if (!checkoutItemsSummary) return;
    checkoutItemsSummary.innerHTML = "";
    
    cart.forEach(item => {
      const itemEl = document.createElement("div");
      itemEl.className = "checkout-summary-item";
      itemEl.innerHTML = `
        <span class="checkout-summary-name">${item.qty}x ${item.name}</span>
        <span class="checkout-summary-price">${(item.price * item.qty).toFixed(2)}€</span>
      `;
      checkoutItemsSummary.appendChild(itemEl);
    });

    updateCartUI();
  }

  // Payment Options Tab Toggle
  paymentOptions.forEach(opt => {
    opt.addEventListener("click", (e) => {
      paymentOptions.forEach(o => o.classList.remove("selected"));
      e.currentTarget.classList.add("selected");
      
      const method = e.currentTarget.getAttribute("data-payment");
      if (method === "card") {
        cardDetailsFields.style.display = "flex";
        // make input required
        cardDetailsFields.querySelectorAll("input").forEach(i => i.required = true);
      } else {
        cardDetailsFields.style.display = "none";
        // remove required
        cardDetailsFields.querySelectorAll("input").forEach(i => i.required = false);
      }
    });
  });

  // Promo Code Validation
  const applyPromo = (code) => {
    const val = code.trim().toUpperCase();
    if (val === "ALBABOSCH10") {
      isDiscountApplied = true;
      const msg = currentLanguage === "en" ? "10% Discount applied!" : currentLanguage === "es" ? "¡10% Descuento aplicado!" : "10% de descompte aplicat!";
      
      if (cartPromoFeedback) {
        cartPromoFeedback.textContent = msg;
        cartPromoFeedback.className = "promo-feedback success";
      }
      if (checkoutPromoFeedback) {
        checkoutPromoFeedback.textContent = msg;
        checkoutPromoFeedback.className = "promo-feedback success";
      }
      if (cartPromoInput) cartPromoInput.value = "ALBABOSCH10";
      if (checkoutPromoInput) checkoutPromoInput.value = "ALBABOSCH10";
      
      updateCartUI();
    } else if (val === "") {
      if (cartPromoFeedback) cartPromoFeedback.textContent = "";
      if (checkoutPromoFeedback) checkoutPromoFeedback.textContent = "";
    } else {
      const msg = currentLanguage === "en" ? "Invalid promo code" : currentLanguage === "es" ? "Código inválido" : "Codi promocional no vàlid";
      if (cartPromoFeedback) {
        cartPromoFeedback.textContent = msg;
        cartPromoFeedback.className = "promo-feedback error";
      }
      if (checkoutPromoFeedback) {
        checkoutPromoFeedback.textContent = msg;
        checkoutPromoFeedback.className = "promo-feedback error";
      }
    }
  };

  if (cartPromoApply && cartPromoInput) {
    cartPromoApply.addEventListener("click", () => {
      applyPromo(cartPromoInput.value);
    });
  }

  if (checkoutPromoApply && checkoutPromoInput) {
    checkoutPromoApply.addEventListener("click", () => {
      applyPromo(checkoutPromoInput.value);
    });
  }

  // Checkout submit simulation
  if (checkoutForm) {
    checkoutForm.addEventListener("submit", (e) => {
      e.preventDefault();
      
      // Simulate API submit
      checkoutMainGrid.style.display = "none";
      checkoutSuccessContainer.style.display = "flex";
      
      // Reset Cart state
      cart = [];
      isDiscountApplied = false;
      if (checkoutPromoInput) checkoutPromoInput.value = "";
      if (checkoutPromoFeedback) checkoutPromoFeedback.textContent = "";
      if (cartPromoInput) cartPromoInput.value = "";
      if (cartPromoFeedback) cartPromoFeedback.textContent = "";
      updateCartUI();
    });
  }
}

